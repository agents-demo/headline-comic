"""Local AniDoodle adapter for keyframes (T023).

Implements the ``ImageProvider`` contract with a deterministic, browser-only
renderer. Each ``ImageRequest.prompt`` carries a JSON scene spec (built by
``src/skills/image_gen``); this provider turns those specs into one AniDoodle
film with one shot per keyframe and renders them with ``still.mjs`` in a single
browser session. It never consumes the reference PNGs — the art comes from the
committed cast library (``scripts/anidoodle/cast/cast.ts``), whose rendered form
*is* the cast sheets — so the ``reference_images`` on a request are kept only for
interface parity with a future paid provider.

The render is local and $0; no approval or network guard applies (see
``src/permissions/approval_guard``).
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

from .contracts import ImageRequest, ImageResult

_RUN_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$")
WIDTH = 1280
HEIGHT = 720


def render_scenes_ts(specs: list[dict]) -> str:
    """Serialize scene specs to the ``scenes.ts`` the AniDoodle film imports."""
    lines = [
        "// Generated by src/providers/anidoodle_image.py — deterministic storyboard -> scene data.",
        "// Regenerated per run from the image_gen mapping; do not edit by hand.",
        "export const scenes = ",
        json.dumps(specs, indent=2),
        ";",
    ]
    return "\n".join(lines) + "\n"


class AniDoodleImageProvider:
    """Render keyframes through the local AniDoodle still path."""

    def __init__(self, repo_root: Path | None = None, anidoodle_home: Path | None = None) -> None:
        self.repo_root = (repo_root or Path(__file__).resolve().parents[2]).resolve()
        self.renderer_script = self.repo_root / "scripts" / "anidoodle" / "render_keyframes.mjs"
        if not self.renderer_script.is_file():
            raise FileNotFoundError(f"AniDoodle keyframe renderer not found: {self.renderer_script}")
        self.anidoodle_home = self._resolve_home(anidoodle_home)

    def _resolve_home(self, explicit: Path | None) -> Path:
        candidate = explicit or (Path(os.environ["ANIDOODLE_HOME"]) if os.environ.get("ANIDOODLE_HOME") else None)
        if candidate is not None and (Path(candidate) / "skills" / "anidoodle" / "engine" / "tools" / "still.mjs").is_file():
            return Path(candidate)
        fallback = self.repo_root / "anidoodle"
        if (fallback / "skills" / "anidoodle" / "engine" / "tools" / "still.mjs").is_file():
            return fallback
        raise RuntimeError("Set ANIDOODLE_HOME to an AniDoodle checkout")

    def _run_id_from(self, requests: list[ImageRequest]) -> str:
        runs_root = self.repo_root / "runs"
        ids: set[str] = set()
        for request in requests:
            path = request.output_path.resolve()
            if not (runs_root.resolve() in path.parents) or path == runs_root.resolve():
                raise ValueError("keyframe output must stay inside runs/<run-id>/")
            ids.add(path.relative_to(runs_root).parts[0])
        if len(ids) != 1:
            raise ValueError("all keyframes in one batch must target the same run directory")
        run_id = ids.pop()
        if not _RUN_ID.fullmatch(run_id):
            raise ValueError("invalid run id derived from output paths")
        return run_id

    def generate(self, request: ImageRequest) -> ImageResult:
        return self.generate_batch([request])[0]

    def generate_batch(self, requests: list[ImageRequest]) -> list[ImageResult]:
        if not requests:
            return []
        run_id = self._run_id_from(requests)
        specs = [json.loads(request.prompt) for request in requests]

        run_dir = self.repo_root / "runs" / run_id
        run_dir.mkdir(parents=True, exist_ok=True)
        (run_dir / "scenes.ts").write_text(render_scenes_ts(specs), encoding="utf-8")
        (run_dir / "scenes.json").write_text(json.dumps(specs, indent=2) + "\n", encoding="utf-8")

        env = os.environ.copy()
        env["ANIDOODLE_HOME"] = str(self.anidoodle_home)
        subprocess.run(
            ["node", str(self.renderer_script), run_id],
            cwd=self.repo_root,
            env=env,
            check=True,
        )

        results: list[ImageResult] = []
        for request, spec in zip(requests, specs):
            shot_id = spec["shot_id"]
            source = run_dir / "anidoodle" / "out" / f"still-keyframes-{shot_id}.png"
            if not source.is_file():
                raise RuntimeError(f"AniDoodle did not produce a keyframe for {shot_id}")
            request.output_path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, request.output_path)
            results.append(ImageResult(image_path=request.output_path, width=WIDTH, height=HEIGHT))
        return results
