"""S13 video_gen: render the short silent video from bounded storyboard data (T027).

Mirrors ``image_gen`` for the still pipeline: a **deterministic mapping** from the
Director's free-text storyboard to the same bounded scene specs ``image_gen``
uses (one per shot, with the shot's storyboard duration attached), then an
**orchestrator** that stages those specs as ``runs/<run>/video_scenes.ts`` and
renders one silent MP4 through the provider-neutral ``VideoProvider`` with retry,
recording the video cost through the T007 budget guard.

The local AniDoodle provider (``src/providers/anidoodle.py``) consumes that scene
data and animates each scene (camera push-in for zoom shots, a pan across the
overhead map) at $0; a paid image-to-video provider can replace it behind the
same ``VideoProvider`` interface and the same budget hook.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping, Sequence

from src.permissions.approval_guard import ApprovalRequired, require_approval
from src.permissions.media_guard import (
    CostRecordError,
    MissingUnitPrice,
    UnitPrice,
    prepare_storyboard_quote,
    record_actual_cost,
    require_allowed_write_path,
)
from src.providers.contracts import VideoRequest, VideoResult
from src.skills.image_gen import scene_spec
from src.skills.video_recovery import run as run_recovery

MAX_DURATION_S = 59.0  # strictly under one minute (FR-010)


class VideoGenError(RuntimeError):
    """Raised when the storyboard cannot be turned into a video render."""


def video_specs(storyboard: Mapping[str, Any]) -> list[dict[str, Any]]:
    """One bounded scene spec per shot, with the shot's storyboard duration."""
    shots = storyboard.get("shots")
    if not isinstance(shots, list) or not shots:
        raise VideoGenError("storyboard must contain a non-empty shots array")
    specs: list[dict[str, Any]] = []
    for shot in shots:
        if not isinstance(shot, Mapping):
            raise VideoGenError("storyboard shot must be an object")
        duration = float(shot.get("duration_s") or 0)
        if not 0 < duration <= MAX_DURATION_S:
            raise VideoGenError(f"shot {shot.get('shot_id')} has invalid duration {duration}")
        spec = dict(scene_spec(shot))
        spec["duration_s"] = duration
        specs.append(spec)
    return specs


def total_duration_s(specs: Sequence[Mapping[str, Any]]) -> float:
    """Sum shot durations; a film of just the shots must stay under one minute."""
    return sum(float(spec["duration_s"]) for spec in specs)


def serialize_video_scenes(specs: Sequence[Mapping[str, Any]]) -> str:
    """Serialize scene specs to the ``videoScenes.ts`` the AniDoodle film imports."""
    lines = [
        "// Generated by src/skills/video_gen.py — deterministic storyboard -> video scene data.",
        "// Regenerated per run; do not edit by hand.",
        "export const videoScenes = ",
        json.dumps(list(specs), indent=2),
        ";",
    ]
    return "\n".join(lines) + "\n"


def _retry(fn: Any, max_attempts: int) -> Any:
    last: Exception | None = None
    for _ in range(max_attempts):
        try:
            return fn()
        except Exception as exc:  # noqa: BLE001 - a provider failure is retried, then surfaced
            last = exc
    assert last is not None
    raise last


def run(
    storyboard: Mapping[str, Any],
    *,
    provider: Any,
    workspace_root: Path,
    run_id: str,
    unit_prices: Mapping[str, UnitPrice],
    max_attempts: int = 2,
    approval_path: Path | None = None,
) -> VideoResult:
    """Render the run's silent video, budgeted and guarded.

    The video unit price is recorded explicitly (``unit_prices["video"]``). A
    non-zero price additionally requires an approval record for the run; the
    local AniDoodle path is $0 and skips that paid-only requirement. The scene
    data is staged under ``runs/<run-id>/video_scenes.ts`` for the provider to
    read, and the video must stay under one minute.
    """
    root = workspace_root.resolve()
    video_price = unit_prices.get("video")
    if video_price is None:
        raise MissingUnitPrice("No recorded unit price for video calls")

    specs = video_specs(storyboard)
    total = total_duration_s(specs)
    if total >= MAX_DURATION_S:
        raise VideoGenError(f"shot durations sum to {total:g}s; must stay under {MAX_DURATION_S:g}s")

    run_dir = root / "runs" / run_id
    require_allowed_write_path(run_dir / "video_scenes.ts", workspace_root=root)

    # Reserve the video line once. When the image stage already reserved the run
    # quote (with ``planned_categories=("image", "video")``), reuse that record;
    # a standalone video-only run reserves the video line itself.
    cost_path = run_dir / "cost.json"
    if cost_path.exists():
        record = json.loads(cost_path.read_text(encoding="utf-8"))
        items = record.get("items") if isinstance(record, dict) else None
        if not isinstance(items, list) or not any(
            isinstance(item, dict) and item.get("category") == "video" for item in items
        ):
            raise CostRecordError(
                "run cost record lacks a video line; reserve the image and video quote together"
            )
    else:
        prepare_storyboard_quote(
            storyboard,
            unit_prices,
            workspace_root=root,
            run_id=run_id,
            planned_categories=["video"],
        )

    if video_price.usd_per_unit > 0:
        if approval_path is None:
            raise ApprovalRequired("Paid video generation requires an approval record")
        require_approval(action="video", approval_path=approval_path, run_id=run_id)

    (run_dir / "video_scenes.ts").write_text(serialize_video_scenes(specs), encoding="utf-8")
    request = VideoRequest(run_id=run_id, max_duration_s=MAX_DURATION_S)
    result = _retry(lambda: provider.render(request), max_attempts)

    actual = video_price.usd_per_unit * len(specs)
    record_actual_cost(workspace_root=root, run_id=run_id, category="video", actual_usd=actual)
    return result


def run_h3(
    story: Mapping[str, Any],
    storyboard: Mapping[str, Any],
    candidates: Mapping[str, Any],
    summaries: Mapping[str, Any],
    *,
    provider: Any,
    workspace_root: Path,
    run_id: str,
    unit_prices: Mapping[str, UnitPrice],
    clips: Sequence[Any] | None = None,
    holds: Mapping[str, float] | None = None,
    ledger: Mapping[str, Any] | None = None,
    bed_path: Path | None = None,
    max_attempts: int = 2,
    approval_path: Path | None = None,
) -> Path:
    """Render each shot through MiniMax-H3 (native audio) and assemble the video (T043).

    The H3 provider is self-hosted, so the video line is reserved at $0 and no T007
    approval record is required. The provider's per-shot ``renderer`` feeds the shared
    recovery seam (retry-once + animated-still swap), and the recovered clips' native
    audio replaces the TTS narration in assembly — the music bed is ducked under it.
    """
    root = workspace_root.resolve()
    video_price = unit_prices.get("video")
    if video_price is None:
        raise MissingUnitPrice("No recorded unit price for video calls")

    run_dir = root / "runs" / run_id
    require_allowed_write_path(run_dir / "video_scenes.ts", workspace_root=root)

    # Reserve the video line once, mirroring the AniDoodle path: reuse the image
    # stage's quote when present, otherwise reserve a video-only quote.
    cost_path = run_dir / "cost.json"
    if cost_path.exists():
        record = json.loads(cost_path.read_text(encoding="utf-8"))
        items = record.get("items") if isinstance(record, dict) else None
        if not isinstance(items, list) or not any(
            isinstance(item, dict) and item.get("category") == "video" for item in items
        ):
            raise CostRecordError(
                "run cost record lacks a video line; reserve the image and video quote together"
            )
    else:
        prepare_storyboard_quote(
            storyboard,
            unit_prices,
            workspace_root=root,
            run_id=run_id,
            planned_categories=["video"],
        )

    if video_price.usd_per_unit > 0:
        if approval_path is None:
            raise ApprovalRequired("Paid video generation requires an approval record")
        require_approval(action="video", approval_path=approval_path, run_id=run_id)

    render = provider.renderer(storyboard, run_dir / "keyframes")
    result = run_recovery(
        story,
        storyboard,
        candidates,
        summaries,
        workspace_root=root,
        run_id=run_id,
        render=render,
        clips=clips,
        holds=holds,
        ledger=ledger,
        bed_path=bed_path,
        native_audio=True,
    )

    shots = storyboard.get("shots")
    count = len(shots) if isinstance(shots, list) else 0
    record_actual_cost(workspace_root=root, run_id=run_id, category="video", actual_usd=video_price.usd_per_unit * count)
    return result
